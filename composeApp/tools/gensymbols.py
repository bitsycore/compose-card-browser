HEADER = '''package com.bitsycore.cardbrowser.ui.common

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathParser
import androidx.compose.ui.unit.dp

/**
 * Every icon this app draws.
 *
 * **Generated by `composeApp/tools/gensymbols.py`. Do not edit.**
 *
 * ## Why the app has no icon dependency
 *
 * `material-icons-extended` is every Material icon there is -- a 36 MB desktop jar and an 18 MB
 * klib per iOS target -- for the handful this app draws. R8 strips the rest from an Android release
 * build; nothing strips them from a desktop distributable or an iOS binary.
 *
 * `material-icons-core` was smaller and was dropped for a different reason: it publishes no klibs
 * for the native desktop targets, so it blocked the Kotlin/Native port for a dozen glyphs. See
 * `docs/NATIVE_DESKTOP.md`.
 *
 * ## Where these come from
 *
 * Material Symbols, downloaded from google/material-design-icons. The `d` attribute of each SVG is
 * copied verbatim and parsed at runtime by Compose's own `PathParser` -- the same parser that reads
 * a vector drawable -- so these are Google's drawings rather than anyone's tracing of them.
 *
 * Apache 2.0, (c) Google.
 */
object AppIcons {
'''

FOOTER = '''}

/**
 * One Material Symbol, built from its SVG path.
 *
 * The group exists to move the drawing onto the canvas. Material Symbols uses a `0 -960 960 960`
 * viewBox -- a 960 grid whose origin is at the *bottom* -- and `ImageVector` has no viewport offset,
 * so the path is translated down by a full grid instead. Nothing is rescaled: the viewport is
 * declared as 960 and the 24dp default size does the scaling, exactly as the source SVG's own
 * `width="24"` does.
 *
 * Parsed once and held by the `by lazy` on each property above, so an icon costs its parse the
 * first time it is drawn and nothing after that.
 */
private fun symbol(name: String, pathData: String, autoMirror: Boolean = false): ImageVector =
	ImageVector.Builder(
		name = "AppIcons.$name",
		defaultWidth = ICON_SIZE,
		defaultHeight = ICON_SIZE,
		viewportWidth = SYMBOL_GRID,
		viewportHeight = SYMBOL_GRID,
		autoMirror = autoMirror,
	)
		.addGroup(translationY = SYMBOL_GRID)
		.addPath(
			pathData = PathParser().parsePathString(pathData).toNodes(),
			// Black, and then tinted by whatever draws it. `Icon` applies `LocalContentColor` over
			// the top, which is how every one of these follows the theme without knowing about it.
			fill = SolidColor(Color.Black),
		)
		.clearGroup()
		.build()

/** The size every Material icon is drawn at, and what the source SVGs declare. */
private val ICON_SIZE = 24.dp

/** Material Symbols' viewBox. See [symbol] for why the origin needs a translation. */
private const val SYMBOL_GRID = 960f
'''


def fetch(symbol, fill):
	"""The `d` attribute of one Material Symbol, verbatim."""
	vVariant = "materialsymbolsoutlined"
	vName = "%s_%s24px.svg" % (symbol, "fill1_" if fill else "")
	vUrl = "%s/%s/%s/%s" % (BASE, symbol, vVariant, vName)
	with urllib.request.urlopen(vUrl, timeout=30) as vResponse:
		vSvg = vResponse.read().decode("utf-8")
	vPaths = re.findall(r'<path[^>]*\sd="([^"]+)"', vSvg)
	if len(vPaths) != 1:
		raise SystemExit("%s: expected one path, found %d" % (vUrl, len(vPaths)))
	return vPaths[0]


def main():
	if not os.path.isdir("composeApp"):
		raise SystemExit("run from the repository root")
	vOut = [HEADER]
	for vName, vSymbol, vFill, vMirror in WANTED:
		vPath = fetch(vSymbol, vFill)
		vMirrorArg = ", autoMirror = true" if vMirror else ""
		vOut.append(
			'\tval %s: ImageVector by lazy { symbol("%s", "%s"%s) }\n'
			% (vName, vName, vPath, vMirrorArg),
		)
	vOut.append(FOOTER)
	io.open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(vOut))
	print("wrote %s: %d icons" % (OUT, len(WANTED)))


if __name__ == "__main__":
	main()
