"""
Generates `AppIcons.kt` from Material Symbols, so the app depends on no icon library at all.

    python composeApp/tools/gensymbols.py

Downloads one SVG per icon from google/material-design-icons and writes the path data into a Kotlin
file. Nothing is redrawn by hand and nothing is traced: the `d` attribute is copied verbatim and
parsed at runtime by Compose's own `PathParser`, which is the same parser that reads a vector
drawable. So what ships is exactly what Google drew.

## Why this replaced reading the library's sources jar

The previous generator lifted path data out of `material-icons-extended`'s sources jar, because at
the time thirteen icons still came from `material-icons-core` and two sources of truth risked two
slightly different drawings of the same glyph.

`material-icons-core` is gone now, and it took that argument with it. It also had to go further than
expected: the generated file used `materialIcon` and `materialPath`, which are *from* that library,
so dropping the dependency broke the twenty-four icons that had nothing to do with it. Everything is
built from `ImageVector.Builder` here instead, and the app has no icon dependency left.

## The 960 grid

Material Symbols ships on a 960x960 viewBox with a *negative* origin -- `0 -960 960 960` -- where
the old Material Icons used `0 0 24 24`. `ImageVector` has no viewport offset, so the path is
wrapped in a group translated down by 960. That is exact: no coordinate is rewritten, only moved.

## Adding one

Add a row to `WANTED` and re-run. `fill = 1` picks the filled variant, which is a different file
rather than a different attribute.
"""
import io
import os
import re
import urllib.request

OUT = "composeApp/src/commonMain/kotlin/com/bitsycore/cardbrowser/ui/common/AppIcons.kt"

BASE = "https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web"

# (Kotlin name, Material Symbols name, fill, auto-mirror)
